"""Explicit node-local extension instances. Core knows no application module names."""
from copy import deepcopy
from .json_values import freeze
from contextlib import contextmanager


def validate_modules(value):
    if not isinstance(value,dict):raise ValueError('Node modules must be an object')
    for name,spec in value.items():
        if not isinstance(name,str) or not name:raise ValueError('Invalid node module name')
        if not isinstance(spec,dict) or set(spec)!={'config','state'}:raise ValueError('Module requires config and state')
        if not isinstance(spec['config'],dict) or not isinstance(spec['state'],dict):raise ValueError('Module config/state must be objects')
    freeze(value)
    return deepcopy(value)


class NodeModule:
    def __init__(self,backend,node,config,state):
        self.backend,self.node,self.config,self.state=backend,node,config,state
        self.owned_tools=set()
        self.listeners=[]
        self.active=True
    def install(self):pass
    def bind(self,application):pass
    def listen(self,app,owner,event,function):
        app.on(owner,event,function);self.listeners.append((app,event,(owner,function)))
    def unmount(self):self.close()
    def close(self):
        self.active=False
        for app,event,entry in self.listeners:
            if entry in app.listeners[event]:app.listeners[event].remove(entry)
        self.listeners.clear()
    def tool(self,name,function,**definition):
        if name in self.node.tools:raise ValueError('Module tool conflicts: '+name)
        def guarded(*args,**kwargs):
            owner=getattr(self,"owner",None)
            if not self.active or (owner and owner not in self.backend.components.enabled):raise PermissionError("Node module is not active")
            return function(*args,**kwargs)
        self.node.register_tool(name,guarded,**definition)
        self.owned_tools.add(name)
        if name not in self.node.expose:self.node.expose.append(name)


class NodeModules:
    def __init__(self,backend,factories):
        self.backend,self.factories=backend,factories
        self.instances={}
        self.application=None
    def create(self,name,node,spec):
        instance=self.factories[name](self.backend,node,spec["config"],spec["state"])
        instance.owner=self.backend.components.module_owners.get(name)
        return instance
    def get(self,node_id,name):return self.instances[(node_id,name)]
    def call(self,node_id,name,operation,arguments=None):
        """Trusted component-to-component operations; never an Agent tool grant."""
        instance=self.get(node_id,name)
        if not instance.active:raise PermissionError('Module is not active')
        return instance.invoke_operation(operation,{} if arguments is None else arguments)
    @contextmanager
    def transaction(self,*node_ids):
        """Rollback selected module state on failure; no external I/O rollback."""
        with self.backend._transaction_lock:
            states=[(m.state,deepcopy(m.state)) for (node,_),m in self.instances.items() if not node_ids or node in node_ids]
            try:yield
            except BaseException:
                for target,snapshot in states:target.clear();target.update(snapshot)
                raise
    def find(self,name):return [instance for (node,module),instance in self.instances.items() if module==name]
    def refresh(self):self.backend.components.graph_loaded(self.backend)
    def clear(self):
        for instance in reversed(list(self.instances.values())):self._remove(instance)
        self.instances.clear()
    def _remove(self,instance,*,unmount=False):
        if unmount:instance.unmount()
        else:instance.close()
        for name in instance.owned_tools:
            instance.node.tools.pop(name,None);instance.node.tool_definitions.pop(name,None)
            instance.node.tool_refusals.pop(name,None)
            instance.node.expose[:]=[item for item in instance.node.expose if item!=name]
    def restore(self):
        self.clear()
        # Instantiate all before install, so explicit references are order-independent.
        for node in self.backend.network.nodes.values():
            validate_modules(node.modules)
            for name,spec in node.modules.items():
                if name not in self.factories:raise ValueError('Missing node module component: '+name)
                self.instances[(node.node_id,name)]=self.create(name,node,spec)
        for instance in self.instances.values():instance.install()
    def mount(self,node_id,name,config=None,state=None,*,bind=True):
        with self.backend._transaction_lock:
            node=self.backend.network.nodes[node_id]
            if name in node.modules:raise ValueError('Module already mounted')
            spec=validate_modules({name:dict(config={} if config is None else config,state={} if state is None else state)})[name]
            if name not in self.factories:raise ValueError('Missing node module component: '+name)
            instance=self.create(name,node,spec)
            node.modules[name]=spec;self.instances[(node_id,name)]=instance
            try:
                instance.install()
                if bind and self.application:instance.bind(self.application)
            except BaseException:
                self._remove(instance);node.modules.pop(name);self.instances.pop((node_id,name));raise
            return instance
    def unmount(self,node_id,name):
        with self.backend._transaction_lock:
            instance=self.instances[(node_id,name)]
            self._remove(instance,unmount=True);self.instances.pop((node_id,name))
            return self.backend.network.nodes[node_id].modules.pop(name)
    def bind(self,application):
        self.application=application
        for instance in sorted(list(self.instances.values()),key=lambda item:getattr(item,"bind_order",0)):
            if instance.active and (not instance.owner or instance.owner in self.backend.components.enabled):instance.bind(application)
