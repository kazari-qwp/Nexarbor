 expect(await child.evaluate(()=>{try{void parent.document.body;return false;}catch{return true;}})).toBe(true);
 await page.evaluate(()=>window.postMessage({protocol:'nexarbor-module-frontend/v1',type:'set-config',id:'伪造',config:{fields:{伪造:true}}},'*'));
 await section.locator(':scope > summary').click();await expect(section.locator('iframe')).toHaveCount(0);
