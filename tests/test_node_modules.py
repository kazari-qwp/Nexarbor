"""Generic node module lifecycle and isolation, independent of NPC rules."""
import unittest
from threading import RLock
from types import SimpleNamespace
from datanet.core.node import Node
from datanet.core.network import Network
from datanet.core.node_modules import NodeModule,NodeModules,validate_modules

class Counter(NodeModule):
    def install(self):self.tool('advance',self.advance,description='counter',parameters={'type':'object'})
    def advance(self):self.state['n']+=self.config['step'];return self.state['n']

class ModuleTests(unittest.TestCase):
    def make(self):
        b=SimpleNamespace(network=Network(),_transaction_lock=RLock(),components=SimpleNamespace(module_owners={'counter':'extension'},enabled={'extension'}))
        for key in ('a','b'):b.network.add_node(Node(key,key,None))
        b.modules=NodeModules(b,{'counter':Counter});return b
    def test_explicit_mount_and_state_are_isolated(self):
        b=self.make();cfg={'step':2};m=b.modules.mount('a','counter',cfg,{'n':0});cfg['step']=90
        self.assertEqual(b.network.nodes['a'].tools['advance'](),2)
        self.assertNotIn('advance',b.network.nodes['b'].tools)
        b.modules.mount('b','counter',{'step':1},{'n':10})
        self.assertEqual(b.network.nodes['b'].tools['advance'](),11)
        self.assertEqual(m.state['n'],2)
    def test_unmount_revokes_captured_function_and_presentation(self):
        b=self.make();b.modules.mount('a','counter',{'step':1},{'n':0});fn=b.network.nodes['a'].tools['advance']
        spec=b.modules.unmount('a','counter')
        self.assertEqual(spec['state'],{'n':0});self.assertEqual(b.network.nodes['a'].expose,[])
        with self.assertRaises(PermissionError):fn()
    def test_component_disable_revokes_function(self):
        b=self.make();b.modules.mount('a','counter',{'step':1},{'n':0});b.components.enabled.clear()
        with self.assertRaises(PermissionError):b.network.nodes['a'].tools['advance']()
    def test_restore_retains_values_rebuilds_functions_and_releases_old(self):
        b=self.make();m=b.modules.mount('a','counter',{'step':3},{'n':4});old=b.network.nodes['a'].tools['advance'];self.assertEqual(old(),7)
        b.modules.restore();self.assertFalse(m.active)
        self.assertEqual(b.network.nodes['a'].tools['advance'](),10)
        with self.assertRaises(PermissionError):old()
        b.modules.clear();self.assertNotIn('advance',b.network.nodes['a'].tools)
    def test_conflict_does_not_remove_existing_tool(self):
        b=self.make();node=b.network.nodes['a'];node.register_tool('advance',lambda:42,description='original',parameters={'type':'object'})
        with self.assertRaises(ValueError):b.modules.mount('a','counter',{'step':1},{'n':0})
        self.assertEqual(node.tools['advance'](),42);self.assertNotIn('counter',node.modules)
    def test_invalid_module_contract_rejected(self):
        b=self.make()
        with self.assertRaises(ValueError):b.modules.mount('a','counter',[],{})
        for value in ([],{'x':{}},{'x':{'config':[],'state':{}}},{'x':{'config':{},'state':{'x':set()}}}):
            with self.assertRaises((ValueError,TypeError)):validate_modules(value)

if __name__=='__main__':unittest.main()
